export const properties: Property[] = seeds.map(({ variant, categories, ...rest }) => {
  const centroid = OUTCODE_CENTROIDS[rest.postcode.split(" ")[0]];
  if (!centroid) {
    throw new Error(`No centroid for outcode in postcode "${rest.postcode}"`);
  }

  // Nudge each listing off the outcode centroid so map pins do not stack.
  const jitter = (seed: string, scale: number) => {
    let hash = 0;
    for (let i = 0; i < seed.length; i++) hash = (hash * 31 + seed.charCodeAt(i)) | 0;
    return ((hash % 1000) / 1000 - 0.5) * scale;
  };

  const defaults =
    rest.type === "flat" || rest.type === "studio" ? FLAT : FULL;

  return {
    ...rest,
    lat: centroid.lat + jitter(rest.id, 0.03),
    lng: centroid.lng + jitter(`${rest.id}x`, 0.05),
    images: gallery(rest.id, variant, categories ?? defaults),
  };
});
