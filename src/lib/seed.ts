/**
 * Builds a gallery from the shared illustration set. `variant` (1-3) picks one
 * of three coordinated palettes so each property's photos look like one shoot.
 */
function gallery(
  propertyId: string,
  variant: 1 | 2 | 3,
  categories: ImageCategory[],
): PropertyImage[] {
  return categories.map((category, index) => ({
    id: `${propertyId}-img-${index + 1}`,
    src: `/images/properties/${category}-${variant}.svg`,
    category,
    alt: `${IMAGE_CATEGORY_LABELS[category]} at ${propertyId.replace(/-/g, " ")}`,
  }));
}

